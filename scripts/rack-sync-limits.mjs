import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { MAX_EQUIPMENT_DEVICES, MAX_EQUIPMENT_RACK_LIMITS } from '@ai-infra/rack';

const path = new URL('../apps/web/src/rack/limits.generated.js', import.meta.url);
const expected = '// Generated by scripts/rack-sync-limits.mjs. Do not edit by hand.\n'
  + `export const MAX_EQUIPMENT_DEVICES = ${MAX_EQUIPMENT_DEVICES};\n`
  + `export const MAX_EQUIPMENT_RACK_LIMITS = ${MAX_EQUIPMENT_RACK_LIMITS};\n`;
if (process.argv.includes('--check')) {
  assert.equal((await readFile(path, 'utf8')).replaceAll('\r\n', '\n'), expected, 'Run node scripts/rack-sync-limits.mjs to synchronize browser limits.');
  console.log('Rack browser inventory limits match the domain.');
} else {
  await writeFile(path, expected);
  console.log('Rack browser inventory limits synchronized.');
}
